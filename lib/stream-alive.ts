/**
 * Проверка, что поток реально отдаётся, а не только «ссылка получена».
 *
 * Источник может честно вернуть ссылки, а видео при этом не пойдёт: VK умеет
 * закрыть раздачу целиком (в ответе `X-VD: session_blocked`), и тогда наш
 * прокси отдаёт 503, а плеер просто стоит с пустым экраном. Ровно это случилось
 * 12.09 с «Офисом»: Alloha ссылки отдавала, кнопка «Смотреть» нажималась, и
 * ничего не грузилось — при том, что Плеер 3 играл эту же серию нормально.
 *
 * Поэтому перед запуском дёргаем мастер-плейлист: он маленький (пара килобайт),
 * проверка занимает доли секунды и сразу говорит, живой источник или нет.
 */
export async function потокЖивой(url: string, таймаутМс = 4500): Promise<boolean> {
  if (!url) return false;
  try {
    const сторож = new AbortController();
    const таймер = setTimeout(() => сторож.abort(), таймаутМс);
    const ответ = await fetch(url, { signal: сторож.signal, cache: "no-store" });
    clearTimeout(таймер);
    if (!ответ.ok) return false;
    // Плейлист обязан начинаться с #EXTM3U. Если пришла страница ошибки или
    // что-то ещё — это не поток, сколько бы ни был код ответа.
    const начало = (await ответ.text()).slice(0, 64).trim();
    return начало.startsWith("#EXTM3U");
  } catch {
    // Сеть, таймаут, обрыв — для нас это «источник не отдаёт».
    return false;
  }
}
