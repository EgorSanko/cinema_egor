import "server-only";
import fs from "fs";
import path from "path";

/**
 * Подарочный PRO: окно акции для всех и триал для новичков.
 *
 * ЗАЧЕМ ИМЕННО ТАК. Соблазн был выдать PRO записью в профиль каждому. Но
 * подписка лежит в users.json, там же реально оплатившие, и снимать её потом
 * пришлось бы массовым скриптом — одна ошибка отнимает PRO у тех, кто
 * заплатил. Поэтому подарок НЕ пишется в базу вообще: статус вычисляется на
 * лету, а по окончании окна всё само возвращается как было.
 *
 * Даты держим в отдельном файле рядом с users.json, а не в коде: продлить или
 * выключить акцию можно за десять секунд, без пересборки сайта.
 */

const ФАЙЛ = path.join(process.cwd(), "promo.json");

export type Акция = {
  /** Включена ли вообще. Выключенная акция игнорируется, даты не важны. */
  включена: boolean;
  /** Начало и конец в миллисекундах. */
  начало: number;
  конец: number;
  /** Повод — показывается в баннере. */
  повод: string;
  /** Сколько дней PRO дарим новичку при регистрации. 0 — не дарим. */
  днейНовичку: number;
};

const ПО_УМОЛЧАНИЮ: Акция = {
  включена: false,
  начало: 0,
  конец: 0,
  повод: "",
  днейНовичку: 3,
};

export function прочитатьАкцию(): Акция {
  try {
    if (fs.existsSync(ФАЙЛ)) {
      const д = JSON.parse(fs.readFileSync(ФАЙЛ, "utf-8"));
      return { ...ПО_УМОЛЧАНИЮ, ...д };
    }
  } catch {
    // Битый или недописанный файл не должен ронять выдачу подписки — просто
    // считаем, что акции нет.
  }
  return ПО_УМОЛЧАНИЮ;
}

/** Идёт ли акция прямо сейчас. Возвращает момент окончания или 0. */
export function акцияДо(сейчас = Date.now()): number {
  const а = прочитатьАкцию();
  if (!а.включена) return 0;
  if (сейчас < а.начало || сейчас >= а.конец) return 0;
  return а.конец;
}

/** До какого момента действует триал новичка, зарегистрированного в `когда`. */
export function триалДо(когда?: number, сейчас = Date.now()): number {
  const а = прочитатьАкцию();
  if (!когда || а.днейНовичку <= 0) return 0;
  const до = когда + а.днейНовичку * 24 * 3600 * 1000;
  return до > сейчас ? до : 0;
}
