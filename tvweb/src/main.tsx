import * as React from "react";
import { render } from "react-dom";
import App from "./App";
import { loadRailsCb } from "@/lib/api";
import "./index.css";

// Ловушка ошибок: на телевизоре нет консоли, и «чёрный экран» неотличим от
// «приложение не запустилось». Ошибку шлём себе картинкой — этот способ
// переживает любые ограничения на запросы.
window.onerror = function (m, src, line, col) {
  try {
    var i = new Image();
    i.src = "/tv-error?m=" + encodeURIComponent("tvweb: " + String(m).slice(0, 220)) +
            "&x=" + encodeURIComponent(String(src || "") + ":" + line + ":" + col);
  } catch (e) {}
  return false;
};

// ЗАМОК ОТ ДВОЙНОГО ЗАПУСКА.
//
// Сборка отдаёт браузеру два приложения: современное (type="module") и старое
// (nomodule). Предполагается, что движок запустит РОВНО ОДНО. Телевизор Егора
// (Samsung, Tizen 5) запускал ОБА: они монтировались в один и тот же контейнер
// и дрались за него. На экране оставалось то, которое в сеть не ходило —
// счётчик показывал «запросов 0/0», хотя в логах сервера лежали честные пять
// ответов. Отсюда и вечное «Загружаю подборки».
//
// Кто успел первым — тот и работает, второй тихо уходит.
function beacon(t: string) {
  try {
    var i = new Image();
    i.src = "/tv-error?m=" + encodeURIComponent("этап: " + t);
  } catch (e) {}
}

var w = window as any;
if (!w.__SAPKEFLY_TV_MOUNTED__) {
  w.__SAPKEFLY_TV_MOUNTED__ = true;

  // Подборки грузим ДО запуска приложения, обычным кодом, не полагаясь на
  // эффекты React. На телевизоре Егора счётчик показывал «запросов 0/0» при
  // живой сети — то есть эффект, который эти запросы делает, не выполнялся
  // вовсе. Так приложение получает данные сразу и от эффектов не зависит.
  var el = document.getElementById("root")!;

  // СИНХРОННАЯ ОТРИСОВКА, как у Deeplex.
  //
  // Раньше здесь был createRoot — новый способ из React 18. Он рисует не сразу,
  // а через собственную очередь, и очередь эта работает на таймерах. На Samsung
  // (Tizen 5) внутри MSX таймеры не срабатывают: по нашим шагам загрузки видно,
  // что запросы проходят, а сигнал из обычного setTimeout не приходит НИКОГДА,
  // тогда как на LG приходит и всё работает. Данные приезжали, а перерисовать
  // экран было нечем — отсюда вечная загрузка ровно на одном телевизоре.
  //
  // Deeplex, который на этом же Samsung работает, собран на React 17 (проверено:
  // в их вендорном чанке 17.0.2), а он рисует синхронно. Старый способ render()
  // в React 18 остался и делает ровно это.
  render(<App initialRails={null} booting />, el);
  // Колбэк, а не обещание: на телевизоре Егора Promise.all не разрешался
  // вовсе, и экран замирал на «готовлю подборки» без единой ошибки.
  loadRailsCb(function (rails) {
    // Перерисовываем тем же синхронным способом — см. пояснение выше.
    // Сигналы ВОКРУГ отрисовки главной: именно на ней Samsung умирал молча.
    // Если придёт «до», но не придёт «после» — падение точно здесь.
    beacon("рисую главную: полок " + rails.length);
    render(<App initialRails={rails} />, el);
    beacon("главная нарисована");

    // ЧАСЫ ЖИЗНИ ВНЕ REACT.
    //
    // Такие же часы внутри компонента не присылают НИ ОДНОГО сигнала, хотя
    // обычные таймеры на странице работают: шаги «таймер 300» и «интервал»
    // доходят с того же телевизора. Значит либо страница гибнет меньше чем за
    // секунду, либо не выполняется код внутри React — а это разные болезни и
    // лечатся по-разному.
    //
    // Эти часы заведены обычным таймером, минуя React. Придут — значит React
    // мёртв, а страница жива. Не придут — значит гибнет вся страница.
    var метки = [1, 2, 4, 8, 15];
    for (var i = 0; i < метки.length; i++) {
      (function (с) {
        setTimeout(function () { beacon("жив вне React: " + с + "с"); }, с * 1000);
      })(метки[i]);
    }
    // Отмечаемся живыми: по этой метке сторож в index.html понимает, что
    // выход рисовать не нужно.
    (window as any).__SAPKEFLY_TV_READY__ = true;
    // Строки проверки загрузки нужны, только пока приложение не запустилось.
    // Как дошли до подборок — убираем, иначе они висят поверх интерфейса.
    try {
      var b = document.getElementById("boot");
      if (b && b.parentNode) b.parentNode.removeChild(b);
    } catch (e) {}
  });
}
